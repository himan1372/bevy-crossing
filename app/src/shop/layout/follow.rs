//! Authored route tables from the three native shop-master move files.
use bevy::prelude::*;

fn count(value: f32, bounds: &[f32]) -> usize {
    bounds.iter().take_while(|&&b| value >= b).count()
}

pub(crate) fn zone(tier: u8, p: Vec3) -> usize {
    match tier {
        1 => {
            let (base, bounds): (usize, &[f32]) = if p.x < 80.0 {
                (0, &[140.0, 220.0])
            } else if p.x < 240.0 {
                (3, &[140.0, 220.0])
            } else if p.x < 360.0 {
                (6, &[140.0, 220.0])
            } else {
                (9, &[120.0, 200.0])
            };
            base + count(p.z, bounds)
        }
        2 => {
            if p.z < 120.0 {
                ((p.x - 40.0) / 80.0) as usize
            } else if p.z < 160.0 {
                5 + count(p.x, &[140.0, 240.0, 280.0, 400.0])
            } else if p.z < 280.0 {
                if p.x < 220.0 {
                    10 + count(p.x, &[140.0])
                } else if p.z < 200.0 {
                    if p.x < 340.0 {
                        12
                    } else {
                        13
                    }
                } else {
                    14 + count(p.x, &[300.0, 380.0])
                }
            } else {
                let zone = count(p.x, &[140.0, 220.0, 300.0, 380.0]);
                zone + if p.z < if zone < 2 { 400.0 } else { 360.0 } {
                    17
                } else {
                    22
                }
            }
        }
        3 => {
            if p.x < 220.0 {
                count(p.z, &[200.0, 320.0, 440.0])
            } else {
                let mut zone = count(p.z, &[280.0, 400.0, 440.0]);
                if zone == 2 && p.x >= 360.0 {
                    zone = 4;
                }
                zone + 4
            }
        }
        _ => 0,
    }
}

pub(crate) fn next(tier: u8, current: usize, player: usize) -> usize {
    match tier {
        1 => CONV_NEXT[current.min(11)][player.min(11)],
        2 => SUPER_NEXT[current.min(26)][player.min(26)],
        3 => DEPART_NEXT[current.min(8)][player.min(8)],
        _ => 0,
    }
}

pub(crate) fn point(tier: u8, zone: usize) -> Vec3 {
    let points: &[(f32, f32)] = match tier {
        1 => &CONV_POINTS,
        2 => &SUPER_POINTS,
        3 => &DEPART_POINTS,
        _ => &[],
    };
    points
        .get(zone)
        .map_or(Vec3::ZERO, |&(x, z)| Vec3::new(x, 0.0, z))
}

pub(crate) fn safe(tier: u8, player: Vec3, current: usize) -> bool {
    match tier {
        1 => player.z > 280.0 && current == 8,
        2 => player.z > 440.0 && (current == 24 || current == 25),
        3 => (player.z > 520.0 && current == 7) || (player.z < 120.0 && current == 4),
        _ => false,
    }
}
