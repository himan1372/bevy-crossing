/// `aNMD_get_zone`: the zone of the unit square (`ux`, `uz` = world position over 40).
pub fn zone(sale: SaleType, ux: i32, uz: i32) -> usize {
    let column = (ux - 1).clamp(0, 9) as usize;
    let row = (uz - 3).clamp(0, 9) as usize;
    usize::from(ZONE[sale as usize][row][column])
}

/// `aNMD_get_next_zone(player_zone, zone)`: where to head next from `zone` to reach `player_zone`.
pub fn next_zone(sale: SaleType, player_zone: usize, zone: usize) -> usize {
    let (table, count): (&[u8], usize) = match sale {
        SaleType::Normal => (&NEXT_NORMAL, 68),
        SaleType::Furniture => (&NEXT_FTR, 60),
        SaleType::Clothing => (&NEXT_CLOTH, 14),
        SaleType::Carpet => (&NEXT_CARPET, 6),
    };
    usize::from(table[zone.min(count - 1) * count + player_zone.min(count - 1)])
}

/// `aNMD_search_player2`: the waypoint (x, z in game units) of `zone`.
pub fn point(sale: SaleType, zone: usize) -> (f32, f32) {
    let (x, z): (&[f32], &[f32]) = match sale {
        SaleType::Normal => (&POS_X_NORMAL, &POS_Z_NORMAL),
        SaleType::Furniture => (&POS_X_FTR, &POS_Z_FTR),
        SaleType::Clothing => (&POS_X_CLOTH, &POS_Z_CLOTH),
        SaleType::Carpet => (&POS_X_CARPET, &POS_Z_CARPET),
    };
    let zone = zone.min(x.len() - 1);
    (x[zone], z[zone])
}
