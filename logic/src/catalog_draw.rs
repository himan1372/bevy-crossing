/// The catalog's scale and height for a furniture index: `None` for the pieces the original
/// draws through another branch (umbrellas, notebooks, dinosaur parts, ...).
pub fn draw_for(ftr_idx: u16) -> Option<(f32, f32)> {
    let (_, kind) = FURNITURE_LIST.iter().find(|(idx, _)| *idx == ftr_idx)?;
    DRAW_DATA.get(usize::from(*kind)).copied()
}

